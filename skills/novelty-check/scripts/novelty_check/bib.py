"""BibTeX entries: from doi.org where possible, otherwise built from the record's metadata."""

from __future__ import annotations

import re

from . import util
from .sources import doi as doi_source

TITLE_SKIP = util.STOPWORDS | {"towards", "toward", "on", "via"}


def cite_key(rec: dict) -> str:
    authors = rec.get("authors") or []
    last = "anon"
    if authors and not authors[0].startswith("("):
        name = re.sub(r"\s+\d{4}$", "", authors[0]).strip()
        if "," in name:
            name = name.split(",")[0]
        else:
            name = name.split()[-1] if name.split() else name
        last = re.sub(r"[^a-z]", "", util.fold_ascii(name).lower()) or "anon"
    year = str(rec.get("year") or "nd")
    word = "untitled"
    for w in util.norm_title(rec.get("title")).split():
        if w not in TITLE_SKIP and not w.isdigit():
            word = w
            break
    return "%s%s%s" % (last, year, word)


def _rekey(entry: str, key: str) -> str:
    return re.sub(r"^\s*@(\w+)\s*\{\s*[^,]*,", lambda m: "@%s{%s," % (m.group(1), key), entry, count=1)


def pretty(entry: str) -> str:
    """Put each field of a one-line entry (as Crossref returns them) on its own line."""
    if "\n" in entry.strip():
        return entry.strip()
    out, depth, i = [], 0, 0
    while i < len(entry):
        ch = entry[i]
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                out.append("\n}")
                i += 1
                continue
        if ch == "," and depth == 1:
            out.append(",\n  ")
            i += 1
            while i < len(entry) and entry[i] == " ":
                i += 1
            continue
        out.append(ch)
        i += 1
    return re.sub(r"[ \t]+\n\}", "\n}", "".join(out)).strip()


def _esc(s: str) -> str:
    return re.sub(r"([&%#_$])", r"\\\1", s or "")


def from_metadata(rec: dict, key: str) -> str:
    vt = rec.get("venue_type")
    fields = [
        ("title", "{%s}" % _esc(rec.get("title") or "")),
        ("author", " and ".join(_esc(a) for a in rec.get("authors") or [])),
    ]
    if rec.get("year"):
        fields.append(("year", str(rec["year"])))
    venue = _esc(rec.get("venue") or "")
    if vt in ("conference", "workshop"):
        kind = "inproceedings"
        fields.append(("booktitle", venue))
    elif vt == "journal":
        kind = "article"
        fields.append(("journal", venue))
    else:
        kind = "misc"
        if venue:
            fields.append(("howpublished", venue))
    arxiv = rec.get("ids", {}).get("arxiv")
    if arxiv:
        fields += [("eprint", arxiv), ("archivePrefix", "arXiv")]
    if rec.get("ids", {}).get("doi"):
        fields.append(("doi", rec["ids"]["doi"]))
    if rec.get("url"):
        fields.append(("url", rec["url"]))
    fields.append(("note", "Generated by novelty-check from %s metadata" % ", ".join(rec.get("found_in") or ["record"])))
    body = ",\n".join("  %s = {%s}" % (k, v) for k, v in fields if v)
    return "@%s{%s,\n%s\n}" % (kind, key, body)


def entry_for(rec: dict, key: str) -> tuple[str, str]:
    """Return (entry, origin) where origin says where the BibTeX came from."""
    rids = rec.get("ids", {})
    candidates = []
    if rids.get("doi"):
        candidates.append(rids["doi"])
    if rids.get("arxiv"):
        candidates.append("10.48550/arXiv." + rids["arxiv"])
    for d in candidates:
        try:
            text = doi_source.bibtex(d)
        except Exception:  # network problems fall back to metadata
            text = None
        if text:
            return pretty(_rekey(text, key)), "doi.org (%s)" % d
    if rec.get("bibtex") and rec["bibtex"].lstrip().startswith("@"):
        return _rekey(rec["bibtex"], key), "OpenReview"
    return from_metadata(rec, key), "generated from metadata"


def unique_keys(recs: list[dict]) -> list[str]:
    seen: dict[str, int] = {}
    out = []
    for rec in recs:
        base = cite_key(rec)
        n = seen.get(base, 0)
        seen[base] = n + 1
        out.append(base if n == 0 else base + "abcdefghijklmnopqrstuvwxyz"[min(n - 1, 25)])
    return out
